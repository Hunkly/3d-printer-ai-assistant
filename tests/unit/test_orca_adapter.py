def test_validate_input_parses_info_output(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    monkeypatch.setattr(
        "print_engineer.adapters.slicer.version.registry_display_version", lambda name: None
    )
    adapter = _adapter(tmp_path)
    model = tmp_path / "cube.stl"
    model.write_text("solid cube\nendsolid cube\n", encoding="utf-8")

    info_output = """\
[cube.stl]
size_x = 20.000000
size_y = 20.000000
size_z = 20.000000
number_of_facets = 12
manifold = yes
number_of_parts =  1
volume = 8000.000488
"""

    def fake_run(cmd: list[str], *, timeout: float) -> ProcResult:
        assert "--info" in cmd
        return ProcResult(
            stdout=info_output,
            stderr="",
            return_code=0,
            timed_out=False,
            killed=False,
            duration_seconds=0.1,
        )

    monkeypatch.setattr("print_engineer.adapters.slicer.base.run_cli", fake_run)
    validation = adapter.validate_input(model)
    assert validation.is_valid
    assert validation.size == (20.0, 20.0, 20.0)
    assert validation.volume_mm3 == pytest.approx(8000.000488)
    assert validation.facets == 12
    assert validation.is_manifold is True


