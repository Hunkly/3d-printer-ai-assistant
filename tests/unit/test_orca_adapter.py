def test_slice_version_mismatch_raises(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    monkeypatch.setattr(
        "print_engineer.adapters.slicer.version.registry_display_version", lambda name: None
    )
    adapter = _adapter(tmp_path, version="2.3.2")
    project = tmp_path / "project.3mf"
    _write_project_3mf(project, "02.07.01.62")
    job = _job(tmp_path)
    job = SliceJob(
        model_path=project,
        profile=job.profile,
        filament=job.filament,
        printer=job.printer,
        timeout_seconds=30.0,
    )
    with pytest.raises(VersionMismatch) as excinfo:
        adapter.slice(job)
    details = excinfo.value.to_dict()["details"]
    assert details["model_version"] == "02.07.01.62"
    assert details["slicer_version"] == "2.3.2"


