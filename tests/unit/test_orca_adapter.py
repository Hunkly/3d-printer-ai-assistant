def test_slice_success_parses_all_stats(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    monkeypatch.setattr(
        "print_engineer.adapters.slicer.version.registry_display_version", lambda name: None
    )
    adapter = _adapter(tmp_path)
    job = _job(tmp_path)

    def fake_run(cmd: list[str], *, timeout: float, cwd: Path | None = None) -> ProcResult:
        assert cwd is not None
        job_dir = Path(cwd)
        (job_dir / "plate_1.gcode").write_text(SAMPLE_GCODE, encoding="utf-8")
        _write_gcode_3mf(job_dir / "cube.gcode.3mf")
        return ProcResult(
            stdout="",
            stderr="",
            return_code=0,
            timed_out=False,
            killed=False,
            duration_seconds=1.5,
        )

    monkeypatch.setattr("print_engineer.adapters.slicer.orca.run_cli", fake_run)
    result = adapter.slice(job)

    assert result.gcode_path is not None
    assert result.gcode_path.is_file()
    assert result.output_3mf is not None
    assert result.output_3mf.is_file()
    assert result.estimated_time_minutes == pytest.approx(28 + 31 / 60)
    assert result.layer_count == 100
    assert result.max_z_height == pytest.approx(20.0)
    assert result.filament_used_mm == pytest.approx(1321.15)
    assert result.filament_used_cm3 == pytest.approx(3.18)
    assert result.filament_density == pytest.approx(1.24)
    assert result.filament_weight_g == pytest.approx(1.24 * 3.18)
    assert result.return_code == 0
    assert tmp_path / "workspace" in result.gcode_path.parents


