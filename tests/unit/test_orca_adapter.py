SAMPLE_GCODE = """\
; HEADER_BLOCK_START
; generated by OrcaSlicer 9.9.9 on 2026-08-15 at 00:00:00
; model printing time: 28m 31s; total estimated time: 28m 33s
; total layer number: 100
; filament_density: 1.24
; max_z_height: 20.00
; HEADER_BLOCK_END

; EXECUTABLE_BLOCK_END

; filament used [mm] = 1321.15
; filament used [cm3] = 3.18
"""


def _fake_orca(tmp_path: Path, version: str = "9.9.9") -> Path:
    exe = tmp_path / "orca-slicer.exe"
    exe.write_bytes(b"MZ fake exe")
    (tmp_path / "OrcaSlicer.dll").write_bytes(
        f"\x00OrcaSlicer {version}\x00".encode()
    )
    return exe


def _adapter(tmp_path: Path, *, version: str = "9.9.9") -> OrcaSlicerAdapter:
    exe = _fake_orca(tmp_path, version)
    return OrcaSlicerAdapter(
        executable=exe,
        workdir=tmp_path / "workspace",
        timeout_seconds=30.0,
    )


def _profiles() -> tuple[ProfileInfo, ProfileInfo, ProfileInfo]:
    machine = ProfileInfo(
        name="Base 0.4 nozzle",
        kind=ProfileKind.PRINTER,
        content='{"type": "machine", "name": "Base 0.4 nozzle", "from": "system"}',
        source=ProfileSource.GENERATED,
        materialized=True,
    )
    process = ProfileInfo(
        name="Standard 0.20",
        kind=ProfileKind.PROCESS,
        content='{"type": "process", "name": "Standard 0.20", "from": "system"}',
        source=ProfileSource.GENERATED,
        compatible_printers=("Base 0.4 nozzle",),
        materialized=True,
    )
    filament = ProfileInfo(
        name="Generic PLA",
        kind=ProfileKind.FILAMENT,
        content='{"type": "filament", "name": "Generic PLA", "from": "system"}',
        source=ProfileSource.GENERATED,
        compatible_printers=("Base 0.4 nozzle",),
        materialized=True,
    )
    return process, filament, machine


def _job(tmp_path: Path, *, with_printer: bool = True) -> SliceJob:
    model = tmp_path / "cube.stl"
    model.write_text("solid cube\nendsolid cube\n", encoding="utf-8")
    process, filament, machine = _profiles()
    return SliceJob(
        model_path=model,
        profile=process,
        filament=filament,
        printer=machine if with_printer else None,
        timeout_seconds=30.0,
    )


def _write_gcode_3mf(path: Path) -> None:
    slice_info = (
        '<?xml version="1.0"?>\n<config><plate>'
        '<metadata key="prediction" value="1713"/>'
        '<metadata key="weight" value=""/>'
        '<filament id="1" type="PLA" used_m="1.32" used_g="0.00"/>'
        "</plate></config>\n"
    )
    with zipfile.ZipFile(path, "w") as archive:
        archive.writestr("Metadata/slice_info.config", slice_info)


def _write_project_3mf(path: Path, version: str) -> None:
    with zipfile.ZipFile(path, "w") as archive:
        archive.writestr(
            "Metadata/project_settings.config",
            json.dumps({"type": "project", "version": version}),
        )


def test_detect_returns_info(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    monkeypatch.setattr(
        "print_engineer.adapters.slicer.version.registry_display_version", lambda name: None
    )
    adapter = _adapter(tmp_path)
    info = adapter.detect()
